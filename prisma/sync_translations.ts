async function syncTranslations() {
  console.log(`🌐 Syncing ${MASTER_TRANSLATIONS.length} translation aliases to Supabase translations_management table...`);

  // Ensure table exists
  await prisma.$executeRawUnsafe(`
    CREATE TABLE IF NOT EXISTS "translations_management" (
      "id" TEXT NOT NULL PRIMARY KEY,
      "alias" TEXT NOT NULL UNIQUE,
      "english" TEXT NOT NULL DEFAULT '',
      "marathi" TEXT NOT NULL DEFAULT '',
      "hindi" TEXT NOT NULL DEFAULT '',
      "module" TEXT NOT NULL DEFAULT 'global',
      "description" TEXT,
      "updated_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
      "created_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
  `);

  let inserted = 0;
  let updated = 0;

  for (const item of MASTER_TRANSLATIONS) {
    const existing: any[] = await prisma.$queryRawUnsafe(
      `SELECT id FROM "translations_management" WHERE "alias" = $1 LIMIT 1`,
      item.alias
    );

    if (existing && existing.length > 0) {
      await prisma.$executeRawUnsafe(
        `UPDATE "translations_management"
         SET "english" = $1, "marathi" = $2, "hindi" = $3, "module" = $4, "description" = $5, "updated_at" = CURRENT_TIMESTAMP
         WHERE "alias" = $6`,
        item.english,
        item.marathi,
        item.hindi,
        item.module,
        item.description || null,
        item.alias
      );
      updated++;
    } else {
      const generatedId = `tm_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`;
      await prisma.$executeRawUnsafe(
        `INSERT INTO "translations_management" ("id", "alias", "english", "marathi", "hindi", "module", "description", "updated_at", "created_at")
         VALUES ($1, $2, $3, $4, $5, $6, $7, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)`,
        generatedId,
        item.alias,
        item.english,
        item.marathi,
        item.hindi,
        item.module,
        item.description || null
      );
      inserted++;
    }
  }

  const countResult: any[] = await prisma.$queryRawUnsafe(
    `SELECT COUNT(*)::int as total FROM "translations_management"`
  );
  const totalInDb = countResult[0]?.total || 0;

  console.log(`✅ Translations Sync Complete!`);
  console.log(`   - Inserted: ${inserted}`);
  console.log(`   - Updated: ${updated}`);
  console.log(`   - Total rows in Supabase translations_management: ${totalInDb}`);
}

syncTranslations()
  .catch((e) => {
    console.error('❌ Error syncing translations:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
